"""Generate PILOT_REVIEW.md from the live case pack, so the owner reviews exactly what would run."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from juicr import cases, pilot

pack = pilot.build_pilot("Gemma-4-E4B-it-GGUF")
acc = pilot.accounting(pack)
L = []
w = L.append
w(f"# Pilot review sheet ({cases.PACK_VERSION})\n")
w(f"Status: **{cases.PACK_STATUS}**. Generated by `scripts/pilot_review.py` from the code that would run. "
  "Nothing here has been executed against real inference. Owner approved fixtures, sampling values and limits as-is on 2026-11-07; running and publishing are NOT yet approved. A1 was admitted after its tool-call compatibility check (2026-11-07).\n")
w("## Needs your decision\n")
w("1. Approve or change the five fixtures below.\n2. Approve the sampling values and limits.\n"
  "3. Approve the order seed and agent-case admission rule.\n4. Approve running the pilot (separate from approving publication).\n")
w("## Sampling and limits (proposed)\n")
w(f"- Model: `{pack['model']}` (llama.cpp/Vulkan when verified at run time), explicit context {pack['load']['ctx_size']}, streaming, one client, one active prediction.")
w(f"- Fixed sampling (the model's own load-time defaults observed 2026-11-07): top_p {cases.SAMPLING_FROZEN['top_p']}, top_k {cases.SAMPLING_FROZEN['top_k']}.")
w(f"- Conditions (temperature): {', '.join(map(str, cases.CONDITIONS))}. Paired seeds: {', '.join(map(str, cases.SEEDS))}. Order RNG seed: {pack['order_rng_seed']}.")
w(f"- Single-response cap: {cases.LIMITS_SINGLE['max_tokens']} output tokens, {cases.LIMITS_SINGLE['deadline_s']} s.")
a = cases.LIMITS_AGENT
w(f"- Agent cap per trial: {a['max_requests']} requests, {a['max_tool_calls']} tool calls, {a['max_tokens']} generated tokens, {a['deadline_s']} s.")
w(f"- Temperature 0.0 may give identical output across seeds; timing repeats are not independent quality samples.\n")
w("## Accounting\n")
w(f"- Top-level trials: **{acc['top_level']}**. Single-response requests: {acc['single_requests']}. Agent requests (max): {acc['agent_requests_max']}. "
  f"**Measured requests (max): {acc['measured_requests_max']}**, plus separately budgeted warmups/probes/retries.")
w("- Owner-approved window and ceiling decided earlier: 60 minutes, 150 requests; 10 min grace; 2 restoration retries.\n")
w("## Cases\n")
for cid, c in cases.CASES.items():
    w(f"### {cid}: {c['workload']} — {c['title']}\n")
    if c.get("admission"):
        w(f"Admission: **{c['admission']}**\n")
    w("```text\n" + c["prompt"] + "\n```\n")
w("### E1 frozen JSON Schema\n\n```json")
import json; w(json.dumps(cases.E1_SCHEMA, indent=1)); w("```\n")
w("## What each oracle checks\n")
w("- **C1:** 21 fixed checks run in the no-network sandbox (examples, empty, shared vs adjacent endpoints, nesting, duplicates, negatives, bool rejection, malformed input, no mutation). Full success needs all 21.")
w("- **D1:** four labelled answers (May 2 [B], $40,000 [A], owner not provided, schedule-only supersession). Inventing an owner is critical. Citation support needs a human.")
w("- **W1:** title + exactly 3 bullets + 100–140 words (frozen whitespace rule), four facts preserved; unsupported guarantees/rollout dates are critical (heuristic, human-reviewed). Audience/clarity and tone need blind human review.")
w("- **E1:** JSON parse and schema reported separately; field accuracy; invented due date is critical; raw output always kept.")
w("- **A1:** four criteria scored separately (valid arguments, recovery, supported answer, no-write compliance); fabricated results or send/save claims are critical.\n")
w("## Order of the 30 trials (matched pairs, randomized)\n")
w("| # | trial | case | temp | seed |\n|---|---|---|---|---|")
for t in pack["trials"]:
    w(f"| {t['order_index']} | {t['trial_id']} | {t['case']} | {t['temperature']} | {t['seed']} |")
open(os.path.join(os.path.dirname(__file__), "..", "PILOT_REVIEW.md"), "w").write("\n".join(L) + "\n")
print("written", len(L), "lines")
